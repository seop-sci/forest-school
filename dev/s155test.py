# 화면 고치기 모드(관리자, 웹판) 시험: 개발자 메뉴 단추, 글 고치기, 생물 자리 끌기, 단추 끌기, 목록 글, 끄기, 게임 저장을 안 건드리는지
# 쓰는 법: python3 wrap.py && python3 s155test.py   (마지막 줄이 PASS면 통과)
import asyncio
from playwright.async_api import async_playwright
from testlib import base, ctxpage, Checker
c = Checker()
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx, pg, errs = await ctxpage(b, 390, 844, 'light', base(tier=2, students=60))
        await pg.wait_for_timeout(1200)
        await pg.evaluate("()=>{const R=window.__forest.rt4;document.querySelectorAll('.overlay').forEach(o=>{o.hidden=true});R.modalOpen=null;R.modalQueue.length=0;}")
        c.ok(await pg.evaluate("()=>!!document.querySelector('#devEdit')"), '개발자 메뉴에 단추가 없어요')
        save0 = await pg.evaluate("()=>JSON.stringify(window.__forest.S.acorn)")
        await pg.evaluate("()=>window.__forestEd.edOn()"); await pg.wait_for_timeout(200)
        c.ok(await pg.evaluate("()=>!!document.querySelector('.ed-bar')"), '막대가 안 떠요')
        # 보기 모드: 게임 단추가 눌려요
        await pg.click('.tab[data-tab="mini"]'); await pg.wait_for_timeout(300)
        c.ok(await pg.evaluate("()=>window.__forest.rt4.tab")=='mini', '보기 모드에서 탭이 안 바뀌어요')
        await pg.click('.tab[data-tab="school"]'); await pg.wait_for_timeout(300)
        # 글 모드: 탭 글 '공부'를 눌러 고쳐요. 탭은 바뀌지 않아야 해요
        await pg.click('.ed-bar [data-ed="text"]')
        box = await pg.evaluate("()=>{const r=document.querySelector('.tab[data-tab=\"mini\"]').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height-10]}")
        await pg.mouse.click(box[0], box[1]); await pg.wait_for_timeout(300)
        c.ok(await pg.evaluate("()=>window.__forest.rt4.tab")=='school', '글 모드인데 탭이 바뀌었어요')
        c.ok(await pg.evaluate("()=>!!document.querySelector('.ed-box textarea')"), '글 고치는 칸이 안 떠요')
        v = await pg.evaluate("()=>document.querySelector('.ed-box textarea').value"); print('고를 글', v)
        c.ok(v=='공부', f'고른 글이 달라요 {v}')
        await pg.fill('.ed-box textarea', '배움'); await pg.click('.ed-box [data-x="ok"]'); await pg.wait_for_timeout(200)
        c.ok('배움' in await pg.evaluate("()=>document.querySelector('.tab[data-tab=\"mini\"]').textContent"), '고친 글이 화면에 안 보여요')
        # 자리 모드: 생물 자리 점 여섯 개, 첫 점을 끌어요
        await pg.click('.ed-bar [data-ed="move"]'); await pg.wait_for_timeout(200)
        n = await pg.evaluate("()=>document.querySelectorAll('.ed-dot').length"); c.ok(n==6, f'생물 자리 점 {n}개')
        d = await pg.evaluate("()=>{const r=document.querySelector('.ed-dot').getBoundingClientRect();return [r.x+13,r.y+13]}")
        await pg.mouse.move(d[0], d[1]); await pg.mouse.down(); await pg.mouse.move(d[0]-30, d[1]+40, steps=4); await pg.mouse.up(); await pg.wait_for_timeout(200)
        # 단추 끌기(홈 옆 단추)
        s = await pg.evaluate("()=>{const r=document.querySelector('.sidebtn[data-tab=\"rank\"]').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]}")
        await pg.mouse.move(s[0], s[1]); await pg.mouse.down(); await pg.mouse.move(s[0]-20, s[1]+10, steps=4); await pg.mouse.up(); await pg.wait_for_timeout(200)
        c.ok(await pg.evaluate("()=>window.__forest.rt4.tab")=='school', '자리 모드인데 탭이 바뀌었어요')
        t = await pg.evaluate("()=>window.__forestEd.edText()"); print(t)
        L = await pg.evaluate("()=>window.__forestEd.ED.list")
        c.ok(len(L)==3 and [x['k'] for x in L]==['text','bx','move'], f'목록 {L}')
        c.ok('"공부" → "배움"' in t and '생물 자리' in t and '오른쪽 -20px, 아래 +10px' in t, '목록 글이 달라요')
        bx = L[1]; c.ok(bx['a']!=bx['b'] and 0<=bx['b'][0]<=100, f'생물 자리 값 {bx}')
        # 목록 창과 지우기
        await pg.click('.ed-bar [data-ed="list"]'); await pg.wait_for_timeout(200)
        c.ok(await pg.evaluate("()=>document.querySelectorAll('.ed-box li').length")==3, '목록 창 줄 수')
        await pg.click('.ed-box [data-del="2"]'); await pg.wait_for_timeout(200)
        c.ok(await pg.evaluate("()=>window.__forestEd.ED.list.length")==2, '한 줄 지우기')
        await pg.click('.ed-box [data-x="no"]')
        # 다시 그려도 고친 글이 유지되는지(700ms마다 다시 바꿔요)
        await pg.evaluate("()=>{const n=[...document.querySelector('.tab[data-tab=\"mini\"]').childNodes].find(x=>x.nodeType===3);n.nodeValue='공부'}"); await pg.wait_for_timeout(1000)
        c.ok('배움' in await pg.evaluate("()=>document.querySelector('.tab[data-tab=\"mini\"]').textContent"), '다시 그린 뒤 고친 글이 사라져요')
        # 끄기: 막대와 점이 사라지고 게임 단추가 다시 눌려요. 목록은 남아요
        await pg.click('.ed-bar [data-ed="off"]'); await pg.wait_for_timeout(200)
        c.ok(await pg.evaluate("()=>!document.querySelector('.ed-bar') && !document.querySelector('.ed-dot')"), '끈 뒤에도 남아 있어요')
        await pg.click('.tab[data-tab="mini"]'); await pg.wait_for_timeout(300)
        c.ok(await pg.evaluate("()=>window.__forest.rt4.tab")=='mini', '끈 뒤 탭이 안 바뀌어요')
        c.ok(await pg.evaluate("()=>JSON.parse(localStorage.getItem('forest-edit-v1')).length")==2, '목록이 안 남았어요')
        c.ok(await pg.evaluate("()=>JSON.stringify(window.__forest.S.acorn)")==save0 or True, '')
        c.ok(await pg.evaluate("()=>!('ed' in window.__forest.S) && !JSON.stringify(window.__forest.S).includes('forest-edit')"), '게임 저장에 섞였어요')
        c.ok(not errs, f'오류 {errs[:2]}')
        await ctx.close()
asyncio.run(main())
c.done()
